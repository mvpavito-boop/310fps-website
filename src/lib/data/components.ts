export type ComponentCategory =
    | 'cpu'
    | 'motherboard'
    | 'ram'
    | 'gpu'
    | 'ssd'
    | 'cooling'
    | 'psu'
    | 'case';

export type SocketType = 'LGA1700' | 'LGA1200' | 'AM5' | 'AM4';

export interface PCComponent {
    id: string;
    category: ComponentCategory;
    name: string;
    price: number;
    image: string;
    specs: Record<string, string>;

    series?: string; // Для табов фильтрации (например, 'AMD RYZEN', 'INTEL Z790')
    description?: string; // Для информационного попапа "i"

    // Поля для логики совместимости
    socket?: SocketType;
    powerDraw?: number; // Энергопотребление компонентов (Ватт)
    coolingPower?: number; // Мощность отвода тепла (Кулеры)
    powerOut?: number; // Мощность БП
    length?: number; // Длина видеокарты
    maxGpuLength?: number; // Макс. длина видеокарты в корпусе

    // Для расчета FPS
    baseFps?: Record<string, number>;
    fpsMultiplier?: number; // для CPU

    // UI Теги
    tags?: string[];
    isDefault?: boolean;
}

