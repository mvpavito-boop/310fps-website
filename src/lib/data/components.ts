// Утилита для получения дефолтной сборки
export const getDefaultConfiguration = (source: PCComponent[] = componentsDB) => {
    const config: Partial<Record<Exclude<ComponentCategory, 'ssd'>, PCComponent> & { ssd: PCComponent[] }> = {};
    const categories: ComponentCategory[] = ['cpu', 'gpu', 'motherboard', 'cooling', 'ram', 'ssd', 'psu', 'case'];

    categories.forEach(cat => {
        const defaultComp = source.find(c => c.category === cat && c.isDefault) || source.find(c => c.category === cat);
        if (defaultComp) {
            if (cat === 'ssd') {
                config[cat] = [defaultComp];
            } else {
                config[cat] = defaultComp;
            }
        }
    });

    return config;
};
